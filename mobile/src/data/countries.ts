/**
 * Country data for phone number entry.
 * Flag emojis from ISO 3166-1 alpha-2 codes.
 */
export interface Country {
  iso: string;
  name: string;
  dialCode: string;
  flag: string;
}

/**
 * Returns the flag emoji for a given ISO 3166-1 alpha-2 country code.
 */
function flag(iso: string): string {
  const offset = 127397;
  return iso
    .toUpperCase()
    .split('')
    .map((char) => String.fromCodePoint(char.charCodeAt(0) + offset))
    .join('');
}

